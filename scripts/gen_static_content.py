"""Regenerates frontend/lib/static-content.js from backend/app/seed_resume.py (the single source of the resume content).
Run from the repo root after editing the seed:   python scripts/gen_static_content.py
The site shows this built-in content whenever the API is asleep or unreachable, so the public pages always open."""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "backend/app/seed_resume.py").read_text()
head = src.split("def seed(")[0]
head = re.sub(r"^from sqlalchemy.*$|^from \.models import .*$", "", head, flags=re.M)
ns: dict = {}
exec(head, ns)

STAMP = "2024-10-01T00:00:00Z"


def row(i, **kw):
    return {"id": i, "status": "published", "sort_order": i - 1, "created_at": STAMP, "updated_at": STAMP, **kw}


def iso(d):
    return d.isoformat() if d else None


skills, n = [], 0
for category, names in ns["SKILLS"]:
    for name in names:
        n += 1
        skills.append(row(n, name=name, category=category, level=None))

data = {
    "profile": row(1, photo_media_id=None, **ns["PROFILE"]),
    "skills": skills,
    "experience": [row(i + 1, **{**e, "start_date": iso(e["start_date"]), "end_date": iso(e["end_date"])}) for i, e in enumerate(ns["EXPERIENCE"])],
    "projects": [row(i + 1, repo_url=None, live_url=None, cover_media_id=None, **p) for i, p in enumerate(ns["PROJECTS"])],
    "services": [row(i + 1, price_note=None, **s) for i, s in enumerate(ns["SERVICES"])],
    "settings": {k: v for k, v in ns["SETTINGS"].items()},
}
out = root / "frontend/lib/static-content.js"
out.write_text(
    "// GENERATED by scripts/gen_static_content.py from backend/app/seed_resume.py. Do not edit by hand.\n"
    "// Shown when the API is asleep or unreachable so the public site always opens.\n"
    "export const STATIC_CONTENT = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n"
)
print(f"wrote {out.relative_to(root)}: {len(skills)} skills, {len(data['experience'])} roles, {len(data['projects'])} project(s), {len(data['services'])} services")
